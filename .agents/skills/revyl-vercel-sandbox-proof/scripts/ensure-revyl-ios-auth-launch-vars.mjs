#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const revylBin = process.env.REVYL_BIN || "revyl";
const minTtlSeconds = Number.parseInt(
  process.env.REVYL_SWIFT_DEMO_REVYL_AUTH_MIN_TTL_SECONDS || "1800",
  10,
);
const nowSeconds = Math.floor(Date.now() / 1000);

const args = new Set(process.argv.slice(2));
const checkOnly = args.has("--check");
const force = args.has("--force");
const jsonMode = args.has("--json");

const configuredKeys = [
  "REVYL_SWIFT_DEMO_TEST_LOGIN_TOKEN",
  "REVYL_SWIFT_DEMO_TEST_ACCESS_TOKEN",
  "REVYL_SWIFT_DEMO_TEST_REFRESH_TOKEN",
  "REVYL_SWIFT_DEMO_TEST_UID_TOKEN",
];

function run(command, commandArgs, options = {}) {
  const { label, ...spawnOptions } = options;
  const result = spawnSync(command, commandArgs, {
    encoding: "utf8",
    ...spawnOptions,
  });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    const stderr = result.stderr?.trim();
    const stdout = result.stdout?.trim();
    const commandLabel = label || `${command} ${commandArgs.join(" ")}`;
    throw new Error(
      `${commandLabel} failed${stderr || stdout ? `: ${stderr || stdout}` : ""}`,
    );
  }

  return result.stdout;
}

function decodeJwtPayload(value) {
  if (typeof value !== "string") return null;
  const parts = value.split(".");
  if (parts.length < 2) return null;

  try {
    const normalized = parts[1].replace(/-/g, "+").replace(/_/g, "/");
    const padded = normalized.padEnd(
      normalized.length + ((4 - (normalized.length % 4)) % 4),
      "=",
    );
    return JSON.parse(Buffer.from(padded, "base64").toString("utf8"));
  } catch {
    return null;
  }
}

function formatTime(seconds) {
  if (!Number.isFinite(seconds)) return null;
  return new Date(seconds * 1000).toISOString();
}

function safePrint(payload, exitCode = 0) {
  if (jsonMode) {
    console.log(JSON.stringify(payload, null, 2));
  } else if (payload.reasons?.length) {
    console.log(`${payload.status}: ${payload.reasons.join("; ")}`);
  } else {
    console.log(payload.status);
  }
  process.exit(exitCode);
}

function parseLaunchVars() {
  const output = run(revylBin, [
    "global",
    "launch-var",
    "list",
    "--show-values",
    "--json",
  ]);
  const payload = JSON.parse(output);
  const rows = Array.isArray(payload.result) ? payload.result : [];
  return new Map(rows.map((row) => [row.key, row]));
}

function rowValue(row) {
  if (!row) return undefined;
  return row.value ?? row.raw_value ?? row.rawValue;
}

function analyzeLaunchVars(launchVars) {
  const reasons = [];
  const expirations = {};

  for (const key of configuredKeys) {
    if (!launchVars.has(key)) {
      reasons.push(`${key} is missing`);
    }
  }

  const marker = rowValue(launchVars.get("REVYL_SWIFT_DEMO_TEST_LOGIN_TOKEN"));
  if (marker !== undefined && marker.toLowerCase() !== "true") {
    reasons.push("REVYL_SWIFT_DEMO_TEST_LOGIN_TOKEN is not true");
  }

  for (const key of [
    "REVYL_SWIFT_DEMO_TEST_ACCESS_TOKEN",
    "REVYL_SWIFT_DEMO_TEST_UID_TOKEN",
  ]) {
    const value = rowValue(launchVars.get(key));
    if (!value) {
      continue;
    }

    const payload = decodeJwtPayload(value);
    const exp = Number(payload?.exp);
    if (!Number.isFinite(exp)) {
      reasons.push(`${key} is not a decodable JWT with exp`);
      continue;
    }

    expirations[key] = formatTime(exp);
    if (exp <= nowSeconds) {
      reasons.push(`${key} expired at ${formatTime(exp)}`);
    } else if (exp - nowSeconds < minTtlSeconds) {
      reasons.push(
        `${key} expires too soon at ${formatTime(exp)} (< ${minTtlSeconds}s)`,
      );
    }
  }

  const refreshToken = rowValue(launchVars.get("REVYL_SWIFT_DEMO_TEST_REFRESH_TOKEN"));
  if (refreshToken !== undefined && refreshToken.trim() === "") {
    reasons.push("REVYL_SWIFT_DEMO_TEST_REFRESH_TOKEN is empty");
  }

  if (force) {
    reasons.push("--force requested");
  }

  return {
    expirations,
    reasons,
    requiresRefresh: reasons.length > 0,
  };
}

function updateOrCreateLaunchVar(launchVars, key, value) {
  const description = "Revyl Swift Demo auth proof launch var; demo value generated by starter preflight.";
  if (launchVars.has(key)) {
    run(revylBin, [
      "global",
      "launch-var",
      "update",
      key,
      "--value",
      value,
      "--description",
      description,
    ], {
      label: `${revylBin} global launch-var update ${key} --value <redacted> --description <redacted>`,
    });
    return "updated";
  }

  run(revylBin, [
    "global",
    "launch-var",
    "create",
    `${key}=${value}`,
    "--description",
    description,
  ], {
    label: `${revylBin} global launch-var create ${key}=<redacted> --description <redacted>`,
  });
  return "created";
}

function mintDemoTokens() {
  const mintPath = resolve(scriptDir, "ios-login-tokens.mjs");
  const output = run(process.execPath, [mintPath], {
    env: process.env,
    label: `${process.execPath} ${mintPath} # values redacted`,
  });
  const tokens = JSON.parse(output);

  for (const key of configuredKeys) {
    if (typeof tokens[key] !== "string" || tokens[key].trim() === "") {
      throw new Error(`token mint did not return ${key}`);
    }
  }

  return tokens;
}

try {
  const launchVars = parseLaunchVars();
  const analysis = analyzeLaunchVars(launchVars);

  if (checkOnly) {
    safePrint(
      {
        status: analysis.requiresRefresh ? "stale" : "fresh",
        keys: configuredKeys,
        expirations: analysis.expirations,
        reasons: analysis.reasons,
      },
      analysis.requiresRefresh ? 2 : 0,
    );
  }

  if (!analysis.requiresRefresh) {
    safePrint({
      status: "fresh",
      keys: configuredKeys,
      expirations: analysis.expirations,
      reasons: [],
    });
  }

  const tokens = mintDemoTokens();
  const actions = {};
  for (const key of configuredKeys) {
    actions[key] = updateOrCreateLaunchVar(launchVars, key, tokens[key]);
  }

  const refreshedVars = new Map(
    configuredKeys.map((key) => [key, { key, value: tokens[key] }]),
  );
  const refreshedAnalysis = analyzeLaunchVars(refreshedVars);

  safePrint({
    status: "refreshed",
    keys: configuredKeys,
    actions,
    expirations: refreshedAnalysis.expirations,
    reasons: analysis.reasons,
  });
} catch (error) {
  safePrint(
    {
      status: "error",
      keys: configuredKeys,
      error: error instanceof Error ? error.message : String(error),
    },
    1,
  );
}

